#!/usr/bin/env python3
"""carbon-skin/elevations.js — two storefront bays of the fictional north face, in the
same format tools/dxf2bay.py writes for the live projects (inches, y up)."""
import json

def fi(v):                                  # inches -> 6'-8 1/4"
    ft, inch = int(v // 12), v - 12 * int(v // 12)
    whole = int(inch); frac = inch - whole
    fr = {0: "", .25: " 1/4", .5: " 1/2", .75: " 3/4"}.get(round(frac * 4) / 4, "")
    return f"{ft}'-{whole}{fr}\""

H = 181.0            # 4.6 m storefront
M = 2.0              # frame member face
def storefront(uid, x, w):
    f, lites = [], []
    f += [[x, 0, M, H], [x + w - M, 0, M, H], [x + M, 0, w - 2 * M, M], [x + M, H - M, w - 2 * M, M]]
    mid = x + w / 2 - M / 2
    f += [[mid, M, M, H - 2 * M]]
    ty = 118.0
    f += [[x + M, ty, w - 2 * M, M]]
    for gx, gw in [(x + M, mid - x - M), (mid + M, x + w - M - mid - M)]:
        lites.append({"t": "glass", "x": round(gx, 2), "y": M, "w": round(gw, 2), "h": ty - M})
        lites.append({"t": "glass", "x": round(gx, 2), "y": ty + M, "w": round(gw, 2), "h": H - M - ty - M})
    return {"unit": uid, "level": "GF", "x": x, "y": 0.0, "w": w, "h": H, "dxfW": fi(w), "dxfH": fi(H),
            "tag": [round(x + w * 0.5, 2), 150.0], "frame": [[round(a, 2) for a in r] for r in f], "panels": [], "lites": lites}

def entry(uid, x, w):
    f, lites = [], []
    f += [[x, 0, M, H], [x + w - M, 0, M, H], [x + M, H - M, w - 2 * M, M]]
    door_w, door_h = 36.0, 96.0
    cx = x + w / 2
    d0 = cx - door_w - M / 2
    f += [[d0 - M, 0, M, H - M], [cx + door_w + M / 2, 0, M, H - M], [cx - M / 2, 0, M, door_h + M]]
    f += [[x + M, door_h + M, w - 2 * M, M]]
    lites.append({"t": "door", "x": d0, "y": 0, "w": door_w, "h": door_h})
    lites.append({"t": "door", "x": cx + M / 2, "y": 0, "w": door_w, "h": door_h})
    for gx, gw in [(x + M, d0 - M - x - M), (cx + door_w + M / 2 + M, x + w - M - (cx + door_w + M / 2 + M))]:
        lites.append({"t": "glass", "x": round(gx, 2), "y": M, "w": round(gw, 2), "h": door_h - M})
    lites.append({"t": "glass", "x": x + M, "y": door_h + 2 * M, "w": w - 2 * M, "h": H - M - door_h - 2 * M})
    return {"unit": uid, "level": "GF", "x": x, "y": 0.0, "w": w, "h": H, "dxfW": fi(w), "dxfH": fi(H),
            "tag": [round(cx, 2), 150.0], "frame": [[round(a, 2) for a in r] for r in f], "panels": [], "lites": lites}

def bay(bid, name, src, parts, pier=12.0):
    ops, x, gaps = [], 0.0, []
    for k, (kind, uid, w) in enumerate(parts):
        if k:
            gaps.append({"axis": "h", "a": x, "b": x + pier, "v": pier, "text": fi(pier),
                         "pairs": [[parts[k - 1][1], uid]], "spans": [[0, H]], "lx": x + pier / 2, "ly": H + 8})
            x += pier
        ops.append(storefront(uid, x, w) if kind == "sf" else entry(uid, x, w))
        x += w
    W = x
    return {"id": bid, "name": name, "source": src, "units": "in", "w": W, "h": H, "openings": ops,
            "doors": [], "byOthers": [], "gaps": gaps, "drawnDims": [],
            "overall": [{"axis": "h", "v": W, "text": fi(W), "lx": W / 2, "ly": H + 22},
                        {"axis": "v", "v": H, "text": fi(H), "lx": -18, "ly": H / 2}]}

B = {}
for bb in [bay("north-1", "SF01–02", "FYC-A401 north elevation.dxf", [("sf", "SF01", 157.5), ("sf", "SF02", 157.5)]),
           bay("north-2", "SF03–04", "FYC-A401 north elevation.dxf", [("sf", "SF03", 157.5), ("sf", "SF04", 157.5)]),
           bay("main-entry", "Main entry", "FYC-A402 main entry.dxf", [("en", "SD01", 252.0)]),
           bay("north-3", "SF08–09", "FYC-A403 north elevation.dxf", [("sf", "SF08", 157.5), ("sf", "SF09", 157.5)]),
           bay("north-5", "SF12–13", "FYC-A403 north elevation.dxf", [("sf", "SF12", 157.5), ("sf", "SF13", 157.5)])]:
    B[bb["id"]] = bb
js = ("/* elevations.js — Carbon Skin demo. Fictional bays in the format tools/dxf2bay.py\n"
      "   writes for live projects (inches, y up). GENERATED by mkelev.py. */\n"
      "window.ELEV_BAYS=" + json.dumps(B, separators=(",", ":")) + ";\n")
open("/home/claude/af-hub/carbon-skin/elevations.js", "w").write(js)
print({k: (v["w"], len(v["openings"])) for k, v in B.items()})
