#!/usr/bin/env python3
"""Writes carbon-skin/project-config.js for the demo project from units.json.
Every name, mark, date and figure is fictional. Dates are written as day offsets
from the day the page is opened, so the demo always has a 'today'."""
import json, random

U = json.load(open("/home/claude/demo/units.json"))
rnd = random.Random(20261118)

# install sequence: north storefront west→east, then west, east, entry door,
# then the metal panel; offsets are working days before today (0 = today)
order = ["SF01", "SF02", "SF03", "SF04", "SF07", "SF08", "SF09", "SF10", "SF15", "SF16",
         "SF18", "SD01", "MP01", "MP02", "MP03", "SF11", "SF12"]
offs = [-29, -29, -27, -26, -22, -21, -19, -16, -15, -13, -12, -10, -8, -6, -5, -3, -1, 0][1:]
installed = dict(zip(order, offs))
ready = {"SF05": "", "SF06": "", "SF13": "", "SF14": "", "SF19": "", "MP04": "", "SD02": ""}
issue = {"SF17": "Sill 6 mm out of level at grid B — shim pack on order",
         "SF20": "Head receptor clashes with the sprinkler main · RFI-07"}

units, pos = [], {}
for u in U:
    st, off, note = "pending", None, ""
    if u["id"] in installed:
        st, off = "installed", installed[u["id"]]
        note = {"Storefront": "Frame + glass", "Door": "Doors hung, hardware to follow",
                "Metal Panel": "Panels + trims"}[u["type"]]
    elif u["id"] in ready:
        st, note = "in-progress", "Material on site"
    elif u["id"] in issue:
        st, off, note = "issue", -4, issue[u["id"]]
    row = {"key": u["id"], "id": u["id"], "type": u["type"], "zone": u["face"], "level": "GF",
           "status": st, "off": off, "louver": "no", "note": note}
    if u["id"] == "SF20":
        row["rfi"] = [{"ref": "RFI-07", "dateOff": -4, "subject": "Head receptor vs sprinkler main at grid A/8", "status": "open", "party": "GC", "response": ""}]
    if u["id"] == "SF17":
        row["rfi"] = [{"ref": "RFI-06", "dateOff": -5, "subject": "Sill out of level at grid B, 6 mm", "status": "open", "party": "Concrete", "response": ""}]
    units.append(row)
    pos[u["id"]] = {"x": u["x"], "y": u["y"]}

carbon = {u["id"]: {"w": u["w"], "h": u["h"], "face": u["face"], "type": u["type"]} for u in U}

js = f"""/* ============================================================
   PROJECT CONFIG — Carbon Skin demo (Foundry Yard C)
   ------------------------------------------------------------
   A FICTIONAL project for the public demo at /carbon-skin/.
   Same tracker code as every live project (core/app.js); only
   this file, the plan images and elevations.js are the demo's.
   Every name, mark, date and figure here is made up. Dates are
   day offsets from the day the page is opened.
   GENERATED by mkconfig.py — edit that, not this.
   ============================================================ */
window.PROJECT = (() => {{
const day = off => {{ if (off == null) return ''; const d = new Date(); d.setDate(d.getDate() + off); return d.toISOString().slice(0, 10); }};
const SEED = {json.dumps(units)};
return {{
  name: 'Foundry Yard C',
  code: 'FYC',
  hubId: 'cs-demo',
  hubUnit: 'units',
  hubScope: 'Facade',
  storageKey:  'carbon_skin_demo_v1',
  baselineKey: 'carbon_skin_demo_v1_baseline',
  langKey:     'carbon_skin_demo_lang',
  fileSlug:    'carbon_skin_demo',
  doorPatterns: ["^SD"],
  interiorPatterns: [],
  scopeKpis: [],
  ringScopes: [],
  requirePlacedMarkers: false,
  floors: [ {{ key: 'GF', name: {{ en: 'Ground Floor', zh: '一层', ko: '지상층' }} }} ],
  migrations: [],
  i18n: {{
    en: {{ header_sub: 'Demo project · fictional data', img_alt_gf: 'Foundry Yard C — Ground Floor Plan', legend_door: 'Door' }},
    zh: {{ header_sub: '演示项目 · 虚构数据', img_alt_gf: 'Foundry Yard C — 一层平面图', legend_door: '门' }},
    ko: {{ header_sub: '데모 프로젝트 · 가상 데이터', img_alt_gf: 'Foundry Yard C — 1층 평면도', legend_door: '도어' }}
  }},
  seedUnits: SEED.map(u => {{ const o = Object.assign({{}}, u, {{ date: day(u.off) }}); delete o.off;
    if (o.rfi) o.rfi = o.rfi.map(r => {{ const x = Object.assign({{}}, r, {{ date: day(r.dateOff) }}); delete x.dateOff; return x; }});
    return o; }}),
  seedLog: [
    {{ date: day(-28), category: 'delivery', categories: ['delivery'], content: 'North storefront frames delivered · 14 units, crate 1 of 2' }},
    {{ date: day(-18), category: 'field-verify', categories: ['field-verify'], content: 'West openings measured with the GC · all within tolerance except SF17 sill' }},
    {{ date: day(-11), category: 'delivery', categories: ['delivery'], content: 'Metal panel batch A on site · MP01 to MP04' }},
    {{ date: day(-4), category: 'gc-inquiry', categories: ['gc-inquiry'], content: 'RFI-07 sent · SF20 head receptor vs sprinkler main' }}
  ],
  defaultPositions: {json.dumps(pos)},
  // Carbon Skin: geometry per unit (metres) for the carbon layer (carbon.js)
  carbonUnits: {json.dumps(carbon)}
}};
}})();
"""
open("/home/claude/af-hub/carbon-skin/project-config.js", "w").write(js)
print(len(units), "units;", sum(1 for u in units if u["status"] == "installed"), "installed")
